"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { useParams } from "next/navigation";
import { api } from "@/lib/api";
import { Spinner, ModeBadge, Disclosure } from "@/components/ui";
import {
  FindingsSection,
  NutritionSection,
  RecommendationsSection,
  DoctorSection,
  type Screening,
} from "@/components/ScreeningView";
import { PageFade, Reveal, Stagger, Item, motion } from "@/components/motion";

const SEV_COLORS: Record<string, { text: string; bar: string; glow: string }> = {
  low: { text: "#059669", bar: "#10b981", glow: "rgba(16,185,129,0.35)" },
  moderate: { text: "#b45309", bar: "#f59e0b", glow: "rgba(245,158,11,0.35)" },
  high: { text: "#dc2626", bar: "#ef4444", glow: "rgba(239,68,68,0.4)" },
};

function ConfRing({ pct, color, size = 96 }: { pct: number; color: string; size?: number }) {
  const r = 40;
  const c = 2 * Math.PI * r;
  const filled = (pct / 100) * c;
  return (
    <svg width={size} height={size} viewBox="0 0 96 96" className="conf-ring">
      <circle cx="48" cy="48" r={r} fill="none" stroke="rgba(255,255,255,0.12)" strokeWidth="9" />
      <motion.circle
        cx="48"
        cy="48"
        r={r}
        fill="none"
        stroke={color}
        strokeWidth="9"
        strokeLinecap="round"
        strokeDasharray={c}
        initial={{ strokeDashoffset: c }}
        animate={{ strokeDashoffset: c - filled }}
        transition={{ duration: 1.4, ease: [0.16, 1, 0.3, 1], delay: 0.4 }}
        style={{ rotate: -90, transformOrigin: "center" }}
      />
    </svg>
  );
}

export default function ScreeningResultPage() {
  const params = useParams();
  const id = params.id;
  const [s, setS] = useState<Screening | null>(null);
  const [err, setErr] = useState("");

  useEffect(() => {
    api<{ screening: Screening }>(`/api/history/${id}`)
      .then((d) => setS(d.screening))
      .catch((e) => setErr(e.message));
  }, [id]);

  if (err) return <div className="container page"><div className="alert alert-danger">{err}</div></div>;
  if (!s) return <div className="container page"><Spinner /></div>;

  const sev = (s.overall_severity || "low").toLowerCase();
  const sevColor = SEV_COLORS[sev] || SEV_COLORS.low;
  const findings = s.predictions?.findings || {};
  const pct = Math.round((s.overall_confidence || 0) * 100);

  return (
    <PageFade>
      <div className="container page">
        <div className="flex-between mb-2">
          <h1 className="page-title">Screening Complete</h1>
          <div className="flex-center">
            <Link className="btn btn-secondary btn-sm" href={`/history/${s.id}`}>View Full Details</Link>
            <Link className="btn btn-outline btn-sm" href="/history">History</Link>
          </div>
        </div>
        <p className="page-sub">Screening #{s.id} · {s.created_at} · {s.screening_type} · Mode: {s.mode === "real" ? "Real CNN" : "Demo / Prototype"}</p>

        {s.mode !== "real" && (
          <div className="demo-banner">
            DEMO / PROTOTYPE AI RESULT — this screening was generated by the built-in
            prototype engine, not a trained medical CNN.
          </div>
        )}

        <Stagger className={`result-hero ${sev} mb-3`} gap={0.14}>
          <Item>
            <div className="result-meta">
              <span>Confidence</span>
            </div>
            <div className="dash-hero-title" style={{ marginTop: 0 }}>
              {s.overall_condition}
            </div>
            <p style={{ maxWidth: 620 }}>{s.summary_text}</p>
            <div className="result-meta">
              <span>Severity: {s.overall_severity}</span>
              <span>Findings: {findingsCount(findings)}</span>
            </div>
          </Item>
          <Item className="result-ring-wrap">
            <div className="result-ring">
              <ConfRing pct={pct} color={sevColor.bar} />
              <div className="result-ring-pct" style={{ color: sevColor.text }}>
                {pct}%
              </div>
            </div>
            <div className="result-ring-label">overall confidence</div>
          </Item>
        </Stagger>

        <Reveal>
          <h2 className="section-title">Multimodal findings</h2>
        </Reveal>
        <Reveal delay={0.1}>
          <FindingsSection findings={findings} />
        </Reveal>

        <Reveal>
          <h2 className="section-title">Recommendations</h2>
        </Reveal>
        <Reveal delay={0.1}>
          <RecommendationsSection rec={s.recommendations} />
        </Reveal>

        <Reveal>
          <h2 className="section-title">Nutrition &amp; hydration</h2>
        </Reveal>
        <Reveal delay={0.1}>
          <NutritionSection nutrition={s.nutrition_insights} />
        </Reveal>

        <Reveal>
          <h2 className="section-title">Doctor recommendation</h2>
        </Reveal>
        <Reveal delay={0.1}>
          <DoctorSection docrec={s.doctor_recommendation} />
        </Reveal>

        <Reveal>
          <div className="card mt-3">
            <h3>Next steps</h3>
            <div className="flex-center mt-2">
              <ModeBadge isDemo={s.mode !== "real"} />
              <Link className="btn btn-primary btn-sm" href={`/screening`}>Start a new screening</Link>
              <Link className="btn btn-secondary btn-sm" href="/reminders">Set a follow-up reminder</Link>
            </div>
          </div>
        </Reveal>

        <div className="mt-3">
          <Disclosure />
        </div>
      </div>
    </PageFade>
  );
}

function findingsCount(findings: Record<string, unknown>) {
  return Object.keys(findings || {}).length;
}